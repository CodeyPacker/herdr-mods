/**
 * A drill for one operator inside a small function, so checks can vary the input.
 * @param {string} id @param {string} title @param {string} operator @param {string} signature
 * @param {string} body @param {string[]} checks @param {string} idea @param {string} kind
 * @returns {import("../types.js").Exercise}
 */
function operation(id, title, operator, signature, body, checks, idea, kind = "BinaryExpression") {
  return {
    id, title,
    prompt: `Write \`${signature}\` using the \`${operator}\` operator.`,
    solution: `function ${signature} {\n  return ${body};\n}`,
    rules: [{ kind, operator, message: `Use the ${operator} operator.` }],
    checks,
    hints: [idea, `Return one expression that uses \`${operator}\`.`, form(`function ${signature} {\n  return ${body.replace(operator, "___")};\n}`)],
  };
}

