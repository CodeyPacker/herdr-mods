/**
 * A type alias built with one utility type and checked at compile time.
 * @param {string} id @param {string} title @param {string} prompt @param {string} solution
 * @param {string} utility @param {string[]} typeChecks @param {[string, string, string]} hints
 * @param {string} [declarations] @returns {import("../types.js").Exercise}
 */
function alias(id, title, prompt, solution, utility, typeChecks, [first, second, skeleton], declarations) {
  return {
    id, title, prompt, solution, typeChecks, declarations,
    rules: [{ kind: "TypeReference", name: utility, message: `Use ${utility}<...>.` }],
    hints: [first, second, form(skeleton)],
  };
}

