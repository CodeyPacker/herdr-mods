import { form } from "./form.js";

/**
 * A drill for one string method, called inside a small function so checks can vary the input.
 * @param {string} id @param {string} title @param {string} methodName @param {string} signature
 * @param {string} body @param {string[]} checks @param {string} idea
 * @returns {import("../types.js").Exercise}
 */
function method(id, title, methodName, signature, body, checks, idea) {
  return {
    id, title,
    prompt: `Write \`${signature}\` using the string method \`${methodName}\`.`,
    solution: `function ${signature} {\n  return ${body};\n}`,
    rules: [{ kind: "CallExpression", name: methodName, message: `Call ${methodName}.` }],
    checks,
    hints: [idea, `Return the result of calling \`${methodName}\` on the parameter.`, form(`function ${signature} {\n  return ${body.replace(methodName, "___")};\n}`)],
  };
}

